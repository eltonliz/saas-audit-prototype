/**
 * 复刻页面需求说明数据
 * key = 路由路径（与 /tenant/replica/* 对应）
 * markers = 原型页面上的编号标记，每个 marker 含编号 + 标题 + 详细需求说明
 */

export interface ReplicaMarker {
  /** 编号 1, 2, 3... */
  no: number
  /** 标题（简短） */
  title: string
  /** 字段名（指原型上哪个字段被改） */
  field?: string
  /** 改动类型：新增/修改/删除/业务约束 */
  type: 'new' | 'modify' | 'delete' | 'constraint'
  /** 详细需求说明 */
  description: string
  /** 前置条件 */
  precondition?: string
  /** 后置条件 */
  postcondition?: string
  /** 业务规则 */
  rules?: string[]
  /** 异常场景 */
  exceptions?: { scene: string, handle: string }[]
}

export interface ReplicaPageRequirement {
  /** 页面标题 */
  title: string
  /** SaaS 线上路径 */
  sourcePath?: string
  /** 改动点 markers */
  markers: ReplicaMarker[]
  /** 页面级需求说明（PRD §31 字段规范·纯业务语言，只写页面导航内的页面） */
  spec?: PageSpec
  /** 弹窗/抽屉级需求说明（key 与 page-registry 的 modal key 一致） */
  modals?: Record<string, ModalSpec>
}

/** 弹窗/抽屉级需求说明（页面导航二级菜单项一一对应·纯业务语言） */
export interface ModalSpec {
  /** 需求名称（与菜单项一致） */
  name: string
  /** 用途概述 */
  summary: string
  /** 前置条件 */
  pre: string
  /** 关键配置项/字段说明 */
  fields?: { name: string, desc: string, tag?: '线上原有' | '业务新增' }[]
  /** 业务流程步骤 */
  flow: string[]
  /** 业务规则 */
  rules?: string[]
  /** 异常场景与解决方法 */
  exceptions?: { scene: string, handle: string }[]
}

/** 页面级需求说明（PRD §31 字段规范·纯业务语言） */
export interface PageSpec {
  /** 需求名称 */
  name: string
  /** 页面概述 */
  summary: string
  /** 前置条件：进入该功能的完整前提 */
  pre: string
  /** 后置条件：操作完成后的状态变化 */
  post: string
  /** 备用流程：异常/分支流程 */
  altFlows: string[]
  /** 数据流转：从哪来 → 怎么处理 → 到哪去 */
  dataFlow: string
  /** 上中下游影响 */
  impact: string
  /** 字段说明：字段名 + 说明 + 来源标记 */
  fields: { name: string, desc: string, tag?: '线上原有' | '业务新增' }[]
  /** 业务规则 */
  rules: string[]
  /** 业务流程步骤 */
  businessFlow: string[]
  /** 异常场景与解决方法：研发需在实现中兜底的边界情况 */
  exceptions?: { scene: string, handle: string }[]
}

