lines = src.split('\n')
remaining = set(UP.keys())
ok, fail = 0, []
while remaining:
    positions = {}
    for i, ln in enumerate(lines):
        for k in remaining:
            if ln.startswith("  '" + k + "': {"):
                positions[k] = i
    if not positions:
        fail.extend('nofound:' + k for k in remaining)
        break
    k = max(positions, key=positions.get)
    st = positions[k]
    en = len(lines)
    for j in range(st + 1, len(lines)):
        if lines[j].startswith("  '/tenant/"):
            en = j
            break
    impact, exs = UP[k]
    seg = lines[st:en]
    rep = False
    for i, ln in enumerate(seg):
        if re.match(r"\s*impact: '", ln):
            seg[i] = "      impact: '" + impact.replace("'", "\\'") + "',"
            rep = True
            break
    if not rep:
        fail.append(k + ':impact')
        remaining.discard(k)
        continue
    if exs:
        ins_at = None
        for i, ln in enumerate(seg):
            if ln.strip() == 'exceptions: [':
                ins_at = i
                break
        if ins_at is not None:
            j = ins_at + 1
            while j < len(seg) and seg[j].strip() != '],':
                j += 1
            ins = [seg[ins_at]]
            for s, h in exs:
                ins.append("        { scene: '" + s.replace("'", "\\'") + "', handle: '" + h.replace("'", "\\'") + "' },")
            seg = seg[:ins_at] + ins + seg[j:]
    lines[st:en] = seg
    remaining.discard(k)
    ok += 1
src = '\n'.join(lines)
io.open(F, 'w', encoding='utf-8').write(src)
sys.stdout.write('ok=%d fail=%s clean=%d\n%s' % (ok, ','.join(fail) or '-', len(log), '\n'.join(log[:6])))
