v142 = '| v1.4.2 | 2026-08-28 | **资质审核暂缓 + 残留清理**：①讲师/助教资质审核流程暂不启用——组织管理建档即生效（review_status 恒为 approved），课程库讲师下拉/营期助教下拉直接可选，审核管理页对讲师/助教仅保留档案查看；字段与状态机保留供后续开启 ②全文清理打卡/积分残留：学习链路改为「报名→支付→学习→测验→证书」，激励闭环仅保留红包（复用营销域），发证依据不含打卡完成率 ③排课逻辑明确：仅草稿/待审核营期可编辑排课，审核通过即锁定（复制营期重做）；新增直播草稿营期排课演示数据 ④提现审核：凭证号改选填，打款凭证图片必填（1-3张），新增批量提现统一凭证 ⑤分成记录新增字段口径（分成基数/应分金额/调整金额/净应分）表头问号悬浮解释 ⑥数据看板：主讲统计与助教统计字段对齐，全部统计明细表加分页器，营期/课程统计移除状态列 ⑦移除"日历排课"等与原型不一致的表述，PRD 与原型需求面板一一对齐。 |'
m = re.search(r'(\| v1\.4\.1 \|)', s)
if m:
    s = s[:m.start()] + v142 + '\n' + s[m.start():]
    log.append('v1.4.2 inserted')
else:
    log.append('MISS v1.4.1 anchor')

io.open(F, 'w', encoding='utf-8').write(s)
