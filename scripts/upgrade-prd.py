    ('营期/排课/报名/打卡/邀请码/分组/总测验', '营期/排课/报名/邀请码/分组/总测验'),
    ('积分（打卡+完播/答题）+ 红包（完播/答题/新成员）', '红包（完播/答题/新成员，复用营销域）'),
